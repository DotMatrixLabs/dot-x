import { Project, SourceFile, InterfaceDeclaration } from 'ts-morph';
import { writeFileSync } from 'fs';
import { join, resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

export function generatePluginTypes() {
  const project = new Project();
  const schemaPath = resolve(__dirname, '../src/plugin-api/schema.ts');
  const sourceFile = project.addSourceFileAtPath(schemaPath);
  
  // Extract PluginAPI interface
  const apiInterface = sourceFile.getInterface('PluginAPI');
  
  if (!apiInterface) {
    throw new Error('PluginAPI interface not found in schema.ts');
  }
  
  // Generate client types and implementation
  const clientCode = generateClientCode(apiInterface);
  
  // Write to npm package
  const outputPath = resolve(__dirname, '..', 'plugin-sdk', 'src', 'generated', 'types.ts');
  writeFileSync(outputPath, clientCode);
  
  console.log('✅ Plugin types generated successfully');
}

function generateClientCode(apiInterface: InterfaceDeclaration): string {
  const sourceFile = apiInterface.getSourceFile();
  
  // Get all type aliases and interfaces from the schema file
  const typeAliases = sourceFile.getTypeAliases();
  const interfaces = sourceFile.getInterfaces();
  
  // Extract all type definitions including PluginAPI
  const typeDefinitions: string[] = [];
  
  interfaces.forEach(iface => {
    typeDefinitions.push(iface.getText());
  });
  
  typeAliases.forEach(typeAlias => {
    typeDefinitions.push(typeAlias.getText());
  });
  
  return `// Auto-generated types from src/plugin-api/schema.ts
// Do not edit this file manually

${typeDefinitions.join('\n\n')}

export interface APIClientInterface extends PluginAPI {
  // Extended client interface for internal use
}
`;
}

// Run the generator if this file is executed directly
if (process.argv[1] && process.argv[1].endsWith('generate-plugin-types.ts')) {
  generatePluginTypes();
}