import { Project, SourceFile, InterfaceDeclaration } from 'ts-morph';
import { writeFileSync } from 'fs';
import { join } from 'path';

export function generatePluginTypes() {
  const project = new Project();
  const sourceFile = project.addSourceFileAtPath('src/plugin-api/schema.ts');
  
  // Extract PluginAPI interface
  const apiInterface = sourceFile.getInterface('PluginAPI');
  
  if (!apiInterface) {
    throw new Error('PluginAPI interface not found in schema.ts');
  }
  
  // Generate client types and implementation
  const clientCode = generateClientCode(apiInterface);
  
  // Write to npm package
  const outputPath = join('plugin-sdk', 'src', 'generated', 'types.ts');
  writeFileSync(outputPath, clientCode);
  
  console.log('✅ Plugin types generated successfully');
}

function generateClientCode(apiInterface: InterfaceDeclaration): string {
  const interfaceText = apiInterface.getText();
  
  return `// Auto-generated types from src/plugin-api/schema.ts
// Do not edit this file manually

${interfaceText}

export interface APIClientInterface extends PluginAPI {
  // Extended client interface for internal use
}
`;
}

// Run the generator if this file is executed directly
if (process.argv[1] && process.argv[1].endsWith('generate-plugin-types.ts')) {
  generatePluginTypes();
}